检查手机号是否合法
长度11位 全部是数字 必须1开头 第二位3589
^1[3589][0-9]{9}$
^表示开始
$表示结束
[]一组可能会出现的字符
{}匹配次数
{A,B} 最少匹配A次,最多匹配B次
{A,}最少匹配A次,最多无数次
+ 匹配一次或者无数次
* 匹配0次或者无数次
? 匹配0次或者1次
\ 转义字符
- 表示区间 0-9匹配所有数字
\d 表示所有的数字0-9
--小写转大写表示取反 \d 数字 \D 非数字
\w 表示所有数字,小写字母,大写字母[0-9A-Za-z]
.  表示任意字符
|  表示或者的意思
() 表示一组正则表达式
[^] 表示取反 [^0-9]非数字

















